def default_scene_title(index: int) -> str:
    return tr("scene_badge", index=index)


def default_project_name() -> str:
    return tr("default_project_name")


def is_default_project_name(name: str) -> bool:
    value = (name or "").strip()
    if not value:
        return False
    return value.casefold() in {"nuevo proyecto".casefold(), "new project".casefold()}


def localize_project_name(name: str) -> str:
    clean = (name or "").strip()
    return default_project_name() if is_default_project_name(clean) else (clean or default_project_name())


def is_default_scene_title(title: str, index: int | None = None) -> bool:
    value = (title or "").strip()
    if not value:
        return False
    import re
    m = re.fullmatch(r"(?i)(escena|scene)\s+(\d+)", value)
    if not m:
        return False
    if index is None:
        return True
    try:
        return int(m.group(2)) == int(index)
    except Exception:
        return False


def localize_scene_title(title: str, index: int) -> str:
    return default_scene_title(index) if is_default_scene_title(title, index) else ((title or "").strip() or default_scene_title(index))


def get_language() -> str:
    return getattr(config, "CURRENT_UI_LANGUAGE", config.DEFAULT_UI_LANGUAGE)


def set_language(lang: str) -> None:
    config.CURRENT_UI_LANGUAGE = "en" if lang == "en" else "es"


def load_saved_language() -> str:
    try:
        from app.services.settings_service import SettingsService
        lang = SettingsService.get_ui_language()
    except Exception:
        lang = config.DEFAULT_UI_LANGUAGE
    set_language(lang)
    return get_language()


def tr(key: str, **kwargs) -> str:
    lang = get_language()
    text = TRANSLATIONS.get(lang, TRANSLATIONS["es"]).get(key, TRANSLATIONS["es"].get(key, key))
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text


def ui(en: str, es: str) -> str:
    return es if get_language() == "es" else en


def typology_options() -> list[tuple[str, str]]:
    return [(key, tr(label_key)) for key, label_key in TYPOLOGY_KEYS]


def discourse_options() -> list[tuple[str, str]]:
    return [(key, tr(label_key)) for key, label_key in DISCOURSE_KEYS]
